    private Goal placementGoal(BetterBlockPos pos, BuilderCalculationContext bcc) {
        if (ctx.world().getBlock(pos.x, pos.y, pos.z) != Blocks.air) {
            return new GoalPlace(pos);
        }
        boolean allowSameLevel = ctx.world().getBlock(pos.x, pos.y + 1, pos.z) != Blocks.air;
        BlockState current = bcc.bsi.get0(pos);
        for (ForgeDirection facing : Movement.HORIZONTALS_BUT_ALSO_DOWN_____SO_EVERY_DIRECTION_EXCEPT_UP) {
            BetterBlockPos adj = pos.relative(facing);
            if (MovementHelper.canPlaceAgainst(ctx, adj) && placementPlausible(pos, bcc.getSchematic(pos.x, pos.y, pos.z, current))) {
                return new GoalAdjacent(pos, adj, allowSameLevel);
            }
        }
        return new GoalPlace(pos);
    }

    private Goal breakGoal(BetterBlockPos pos, BuilderCalculationContext bcc) {
        if (Baritone.settings().goalBreakFromAbove.value && bcc.bsi.get0(pos.above()).getBlock() == Blocks.air && bcc.bsi.get0(pos.above(2)).getBlock() == Blocks.air) {
            return new JankyGoalComposite(new GoalBreak(pos), new GoalGetToBlock(pos.above()) {
                @Override
                public boolean isInGoal(int x, int y, int z) {
                    if (y > this.y || (x == this.x && y == this.y && z == this.z)) {
                        return false;
                    }
                    return super.isInGoal(x, y, z);
                }
            });
        }
        return new GoalBreak(pos);
    }

    public static class GoalAdjacent extends GoalGetToBlock {

        private boolean allowSameLevel;
        private BetterBlockPos no;

        public GoalAdjacent(BetterBlockPos pos, BetterBlockPos no, boolean allowSameLevel) {
            super(pos);
            this.no = no;
            this.allowSameLevel = allowSameLevel;
        }

        @Override
        public boolean isInGoal(int x, int y, int z) {
            if (x == this.x && y == this.y && z == this.z) {
                return false;
            }
            if (x == no.x && y == no.y && z == no.z) {
                return false;
            }
            if (!allowSameLevel && y == this.y - 1) {
                return false;
            }
            if (y < this.y - 1) {
                return false;
            }
            return super.isInGoal(x, y, z);
        }

        @Override
        public double heuristic(int x, int y, int z) {
            return this.y * 100 + super.heuristic(x, y, z);
        }

        @Override
        public boolean equals(Object o) {
            if (!super.equals(o)) {
                return false;
            }

            GoalAdjacent goal = (GoalAdjacent) o;
            return allowSameLevel == goal.allowSameLevel
                    && Objects.equals(no, goal.no);
        }

        @Override
        public int hashCode() {
            int hash = 806368046;
            hash = hash * 1412661222 + super.hashCode();
            hash = hash * 1730799370 + (int) BetterBlockPos.longHash(no.x, no.y, no.z);
            hash = hash * 260592149 + (allowSameLevel ? -1314802005 : 1565710265);
            return hash;
        }

        @Override
        public String toString() {
            return String.format(
                    "GoalAdjacent{x=%s,y=%s,z=%s}",
                    SettingsUtil.maybeCensor(x),
                    SettingsUtil.maybeCensor(y),
                    SettingsUtil.maybeCensor(z)
            );
        }
    }

