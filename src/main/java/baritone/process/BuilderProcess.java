    @Override
    public boolean build(String name, File schematic, BetterBlockPos origin) {
        Optional<ISchematicFormat> format = SchematicSystem.INSTANCE.getByFile(schematic);
        if (!format.isPresent()) {
            return false;
        }
        IStaticSchematic parsed;
        try {
            parsed = format.get().parse(new FileInputStream(schematic));
        } catch (Exception e) {
            e.printStackTrace();
            return false;
        }
        ISchematic schem = applyMapArtAndSelection(origin, parsed);
        build(name, schem, origin);
        return true;
    }

    private ISchematic applyMapArtAndSelection(BetterBlockPos origin, IStaticSchematic parsed) {
        ISchematic schem = parsed;
        if (Baritone.settings().mapArtMode.value) {
            schem = new MapArtSchematic(parsed);
        }
        if (Baritone.settings().buildOnlySelection.value) {
            schem = new SelectionSchematic(schem, origin, baritone.getSelectionManager().getSelections());
        }
        return schem;
    }

    @Override
    public void buildOpenSchematic() {
        if (SchematicaHelper.isSchematicaPresent()) {
            Optional<Pair<IStaticSchematic, BetterBlockPos>> schem = SchematicaHelper.getOpenSchematic();
            if (schem.isPresent()) {
                IStaticSchematic raw = schem.get().first();
                BetterBlockPos orig = schem.get().second();
                ISchematic s = applyMapArtAndSelection(orig, raw);
                this.build(raw.toString(), s, orig);
            } else {
                logDirect("No schematic currently open");
            }
        } else {
            logDirect("Schematica is not present");
        }
    }

    @Override
    public void buildOpenLitematic(int i) {
        if (LitematicaHelper.isLitematicaPresent()) {
            if (LitematicaHelper.hasLoadedSchematic(i)) {
                Pair<IStaticSchematic, BetterBlockPos> schem = LitematicaHelper.getSchematic(i);
                BetterBlockPos correctedOrigin = schem.second();
                ISchematic s2 = applyMapArtAndSelection(correctedOrigin, schem.first());
                build(schem.first().toString(), s2, correctedOrigin);
            } else {
                logDirect(String.format("List of placements has no entry %s", i + 1));
            }
        } else {
            logDirect("Litematica is not present");
        }
    }

    @Override
    public void clearArea(BetterBlockPos corner1, BetterBlockPos corner2) {
        BetterBlockPos orig = new BetterBlockPos(Math.min(corner1.x, corner2.x), Math.min(corner1.y, corner2.y), Math.min(corner1.z, corner2.z));
        int widthX = Math.abs(corner1.x - corner2.x) + 1;
        int heightY = Math.abs(corner1.y - corner2.y) + 1;
        int lengthZ = Math.abs(corner1.z - corner2.z) + 1;
        build("clear area", new FillSchematic(widthX, heightY, lengthZ, new BlockState(Blocks.air, 0)), orig);
    }

